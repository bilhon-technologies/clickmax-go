const header = "// Code generated by clickmax-go/internal/generator. DO NOT EDIT.\n\n"

type file struct {
	name    string
	body    bytes.Buffer
	imports map[string]bool
}

func (f *file) printf(format string, args ...any) {
	fmt.Fprintf(&f.body, format, args...)
}

var slugRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]*$`)

// buildTags are the file name suffixes go/build reads as GOOS/GOARCH constraints; a resource file
// ending in one would only compile on that platform.
var buildTags = strings.Fields(`aix android darwin dragonfly freebsd hurd illumos ios js linux nacl
	netbsd openbsd plan9 solaris wasip1 windows zos 386 amd64 amd64p32 arm armbe arm64 arm64be
	loong64 mips mipsle mips64 mips64le mips64p32 mips64p32le ppc ppc64 ppc64le riscv riscv64 s390
	s390x sparc sparc64 wasm`)

func fileName(slug string) (string, error) {
	if !slugRe.MatchString(slug) {
		return "", fmt.Errorf("resource %q cannot be a file name", slug)
	}
	stem := strings.ReplaceAll(slug, "-", "_")
	parts := strings.Split(stem, "_")
	if len(parts) > 1 && slices.Contains(buildTags, parts[len(parts)-1]) {
		return "", fmt.Errorf("resource %q would get the build constraint file name %s.gen.go", slug, stem)
	}
	if stem == "client" || stem == "shared" {
		return "", fmt.Errorf("resource %q clashes with %s.gen.go", slug, stem)
	}
	return stem + ".gen.go", nil
}

// render returns the formatted generated files by name.
func render(m *model) (map[string][]byte, error) {
	files := map[string]*file{}
	get := func(name string) *file {
		if files[name] == nil {
			files[name] = &file{name: name, imports: map[string]bool{}}
		}
		return files[name]
	}
	slugFile := map[string]string{"": "client.gen.go"}
	for _, svc := range m.services {
		name, err := fileName(svc.slug)
		if err != nil {
			return nil, err
		}
		for slug, other := range slugFile {
			if other == name {
				return nil, fmt.Errorf("resources %q and %q both map to %s", slug, svc.slug, name)
			}
		}
		slugFile[svc.slug] = name
	}

	cf := get("client.gen.go")
	writeClient(cf, m)
	for _, mt := range m.root {
		if err := writeMethod(cf, "c *Client", "c", mt); err != nil {
			return nil, err
		}
	}
	for _, svc := range m.services {
		f := get(slugFile[svc.slug])
		f.printf("// %sService groups the /%s/* operations. Reach it through [Client.%s].\n", svc.name, svc.slug, svc.name)
		f.printf("type %sService struct {\n\tclient *Client\n}\n\n", svc.name)
		slices.SortFunc(svc.methods, func(a, b *method) int { return strings.Compare(a.name, b.name) })
		for _, mt := range svc.methods {
			if err := writeMethod(f, "s *"+svc.name+"Service", "s.client", mt); err != nil {
				return nil, err
			}
		}
	}
	for _, name := range slices.Sorted(maps.Keys(m.decls)) {
		d := m.decls[name]
		target := "shared.gen.go"
		if len(d.owners) == 1 {
			for owner := range d.owners {
				target = slugFile[owner]
			}
		}
		if err := writeDecl(get(target), d); err != nil {
			return nil, err
		}
	}

	out := map[string][]byte{}
	for name, f := range files {
		var src bytes.Buffer
		src.WriteString(header)
		src.WriteString("package clickmax\n\n")
		if len(f.imports) > 0 {
			src.WriteString("import (\n")
			for _, imp := range slices.Sorted(maps.Keys(f.imports)) {
				fmt.Fprintf(&src, "\t%q\n", imp)
			}
			src.WriteString(")\n\n")
		}
		src.Write(f.body.Bytes())
		formatted, err := format.Source(src.Bytes())
		if err != nil {
			return nil, fmt.Errorf("%s: generated code does not parse: %w", name, err)
		}
		out[name] = formatted
	}
	return out, nil
}

func writeClient(f *file, m *model) {
	f.printf("// Client calls the Clickmax API. Create one with [New]. Each field groups the operations of\n")
	f.printf("// one resource.\n")
	if len(m.root) > 0 {
		f.printf("//\n// The methods of Client are the operations outside any resource.\n")
	}
	f.printf("type Client struct {\n")
	for _, svc := range m.services {
		f.printf("\t// %s groups the /%s/* operations.\n\t%s *%sService\n", svc.name, svc.slug, svc.name, svc.name)
	}
	f.printf("\n\tcfg settings\n}\n\n")
	f.printf("func newClient(cfg settings) *Client {\n\tc := &Client{cfg: cfg}\n")
	for _, svc := range m.services {
		f.printf("\tc.%s = &%sService{client: c}\n", svc.name, svc.name)
	}
	f.printf("\treturn c\n}\n\n")
}

func writeMethod(f *file, recv, client string, mt *method) error {
	f.imports["context"] = true
	var doc []string
	summary := strings.TrimSpace(mt.summary)
	if summary != "" && !strings.ContainsAny(summary[len(summary)-1:], ".!?:") {
		summary += "."
	}
	doc = append(doc, summary, strings.TrimSpace(mt.desc))
	if mt.deprec {
		doc = append(doc, "Deprecated: the API marks this operation as deprecated.")
	}
	doc = append(doc, fmt.Sprintf("Calls %s %s.", mt.httpVerb, mt.path))
	f.printf("%s", comment(doc, ""))

	args := "ctx context.Context"
	query, body := "nil", "nil"
	if mt.params != nil {
		args += ", params " + mt.params.name
		query = "params.values()"
	}
	if mt.body != nil {
		args += ", body " + mt.body.name
		body = "body"
	}
	args += ", opts ...Option"
	call := fmt.Sprintf("%s.do(ctx, %q, %q, %s, %s, &out, opts)", client, mt.httpVerb, mt.path, query, body)
	if isStruct(mt.out) {
		f.printf("func (%s) %s(%s) (*%s, error) {\n\tvar out %s\n\tif err := %s; err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n\n",
			recv, mt.name, args, mt.out.name, mt.out.name, call)
		return nil
	}
	f.printf("func (%s) %s(%s) (%s, error) {\n\tvar out %s\n\tif err := %s; err != nil {\n\t\tvar zero %s\n\t\treturn zero, err\n\t}\n\treturn out, nil\n}\n\n",
		recv, mt.name, args, mt.out.name, mt.out.name, call, mt.out.name)
	return nil
}

func isStruct(d *decl) bool { return d.kind == declStruct }

func writeDecl(f *file, d *decl) error {
	doc := lead(d)
	doc = append(doc, d.doc...)
	if len(d.variants) > 1 {
		var b strings.Builder
		b.WriteString("A value has one of these property sets:\n")
		for _, v := range d.variants {
			fmt.Fprintf(&b, "  - %s\n", strings.Join(v, ", "))
		}
		doc = append(doc, b.String())
	}
	f.printf("%s", comment(doc, ""))
	switch d.kind {
	case declEnum:
		f.printf("type %s string\n\n// Values of [%s].\nconst (\n", d.name, d.name)
		for i, v := range d.values {
			f.printf("\t%s %s = %s\n", d.consts[i], d.name, strconv.Quote(v))
		}
		f.printf(")\n\n")
	case declDefined:
		f.printf("type %s %s\n\n", d.name, typeStr(f, d.under))
	case declStruct:
		f.printf("type %s struct {\n", d.name)
		for _, fl := range d.fields {
			if strings.ContainsAny(fl.jsonName, ",\"`\\") {
				return fmt.Errorf("%s: property %q cannot be written as a JSON tag", d.name, fl.jsonName)
			}
			f.printf("%s", comment([]string{fl.doc}, "\t"))
			typ, omit := fieldType(f, fl)
			tag := fl.jsonName
			if omit {
				tag += ",omitzero"
			}
			f.printf("\t%s %s `json:\"%s\"`\n", fl.name, typ, tag)
		}
		f.printf("}\n\n")
	case declParams:
		f.imports["net/url"] = true
		f.printf("type %s struct {\n", d.name)
		for _, fl := range d.fields {
			f.printf("%s", comment([]string{fl.doc}, "\t"))
			typ := typeStr(f, fl.typ)
			if !fl.required {
				typ = "*" + typ
			}
			f.printf("\t%s %s\n", fl.name, typ)
		}
		f.printf("}\n\nfunc (p %s) values() url.Values {\n\tv := url.Values{}\n", d.name)
		for _, fl := range d.fields {
			ref := "p." + fl.name
			if fl.required {
				ref = "&" + ref
			}
			fn := map[shapeKind]string{kString: "addString", kTime: "addTime", kInt: "addInt", kFloat: "addFloat", kBool: "addBool", kNamed: "addString"}[fl.typ.kind]
			if fl.typ.kind == kNamed {
				ref = "(*string)(" + ref + ")"
			}
			f.printf("\t%s(v, %q, %s)\n", fn, fl.jsonName, ref)
		}
		f.printf("\treturn v\n}\n\n")
	}
	return nil
}

func lead(d *decl) []string {
	if d.paramsOf != "" {
		return []string{d.name + " holds the query parameters of " + d.paramsOf + "."}
	}
	var parts []string
	if len(d.bodyOf) > 0 {
		parts = append(parts, "the request body of "+joinLinks(d.bodyOf))
	}
	if len(d.outOf) > 0 {
		parts = append(parts, "the response of "+joinLinks(d.outOf))
	}
	if len(parts) == 0 {
		return nil
	}
	return []string{d.name + " is " + strings.Join(parts, " and ") + "."}
}

func joinLinks(links []string) string {
	if len(links) == 1 {
		return links[0]
	}
	return strings.Join(links[:len(links)-1], ", ") + " and " + links[len(links)-1]
}

func typeStr(f *file, t *goType) string {
	switch t.kind {
	case kString:
		return "string"
	case kTime:
		f.imports["time"] = true
		return "time.Time"
	case kInt:
		return "int64"
	case kFloat:
		return "float64"
	case kBool:
		return "bool"
	case kAny:
		return "any"
	case kArray:
		return "[]" + elemStr(f, t.elem)
	case kMap:
		return "map[string]" + elemStr(f, t.elem)
	case kNamed:
		return t.decl.name
	}
	panic(fmt.Sprintf("unhandled type kind %d", t.kind))
}

// elemStr writes an array item or map value; a nullable one becomes a pointer so null survives a
// round trip.
func elemStr(f *file, t *goType) string {
	if t.nullable && !nilable(t) {
		return "*" + typeStr(f, t)
	}
	return typeStr(f, t)
}

// nilable types already have a zero value that encodes as null, so they never get a pointer.
func nilable(t *goType) bool {
	switch t.kind {
	case kAny, kArray, kMap:
		return true
	case kNamed:
		return t.decl.kind == declDefined && nilable(t.decl.under)
	}
	return false
}

// fieldType applies the optionality rules: required non-null fields are values, required nullable
// fields are pointers where nil sends null, optional fields are omitted when zero, and optional
// nullable fields of request types use Nullable so a caller can send an explicit null (a nil any
// would be omitted).
func fieldType(f *file, fl *field) (typ string, omit bool) {
	base := typeStr(f, fl.typ)
	optionalNull := !fl.required && fl.nullable && fl.request
	switch {
	case optionalNull:
		return "Nullable[" + base + "]", true
	case nilable(fl.typ):
		return base, !fl.required
	case fl.required && !fl.nullable && !fl.typ.cyclic:
		return base, false
	}
	return "*" + base, !fl.required
}

// comment renders paragraphs as a // comment, skipping empty ones and repeats.
func comment(paragraphs []string, indent string) string {
	var b strings.Builder
	var seen []string
	for _, p := range paragraphs {
		p = strings.TrimSpace(strings.ReplaceAll(p, "\r", ""))
		if p == "" || slices.Contains(seen, p) {
			continue
		}
		if len(seen) > 0 {
			b.WriteString(indent + "//\n")
		}
		seen = append(seen, p)
		for _, line := range strings.Split(p, "\n") {
			for _, l := range wrap(strings.TrimRight(line, " \t"), 100-len(indent)*4) {
				if l == "" {
					b.WriteString(indent + "//\n")
				} else {
					b.WriteString(indent + "// " + l + "\n")
				}
			}
		}
	}
	return b.String()
}

var listStart = regexp.MustCompile(`^([-*+#>|]|\d+[.)])`)

// wrap breaks prose lines at width. Lines that godoc reads as lists, code or headings are left
// alone, and a break never lands where the next line would start reading as one.
func wrap(line string, width int) []string {
	if len(line) <= width || line[0] == ' ' || line[0] == '\t' || listStart.MatchString(line) {
		return []string{line}
	}
	var out []string
	cur := ""
	for _, w := range strings.Fields(line) {
		if cur != "" && len(cur)+1+len(w) > width && !listStart.MatchString(w) {
			out = append(out, cur)
			cur = w
			continue
		}
		if cur != "" {
			cur += " "
		}
		cur += w
	}
	return append(out, cur)
}
